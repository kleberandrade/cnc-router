import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";

async function exportGcode(page: import("@playwright/test").Page): Promise<{ text: string; name: string }> {
  const downloadPromise = page.waitForEvent("download");
  await page.getByTestId("export-gcode").click();
  const download = await downloadPromise;
  return { text: await fs.readFile((await download.path()) as string, "utf8"), name: download.suggestedFilename() };
}

test.describe("sprint 14: pós-processadores, G20, furação, hélice", () => {
  test("LinuxCNC post exports .ngc with parenthesis comments and M30; inches switch to G20", async ({ page }) => {
    await page.goto("/");
    await page.getByTestId("add-rectangle").click();
    await page.getByTestId("section-toggle-post").click();
    await page.getByTestId("post").selectOption("linuxcnc");
    const a = await exportGcode(page);
    expect(a.name).toBe("projeto.ngc");
    expect(a.text).toContain("(Generated by Oficina CNC");
    expect(a.text).toContain("G64 P0.01");
    expect(a.text.trim().endsWith("M30 (program end)")).toBe(true);
    await page.getByTestId("export-units").selectOption("inch");
    const b = await exportGcode(page);
    expect(b.text).toContain("G20 (inches)");
    expect(b.text).toContain("G0 Z0.1969"); // 5 mm safe height
    await page.getByTestId("post").selectOption("marlin");
    const c = await exportGcode(page);
    expect(c.name).toBe("projeto.gcode");
    expect(c.text).toContain("M117 Oficina CNC");
    expect(c.text.trim().endsWith("M84 ; desliga motores")).toBe(true);
  });

  test("drill operation for a small circle: plunge at the centre, peck cycle", async ({ page }) => {
    await page.goto("/");
    await page.getByTestId("add-circle").click();
    await page.getByTestId("shape-operation").selectOption("drill");
    await page.getByTestId("section-toggle-cut").click();
    await page.getByTestId("peck-depth").fill("6");
    await page.getByTestId("peck-depth").press("Enter");
    const g = await exportGcode(page);
    expect(g.text).toContain("; Drill");
    // stock 18 mm → pecks at -6, -12, -18
    expect(g.text).toContain("G1 Z-6 F");
    expect(g.text).toContain("G1 Z-12 F");
    expect(g.text).toContain("G1 Z-18 F");
    // circle default is Ø > tool → warning in header
    expect(g.text).toMatch(/WARNING: .*furo Ø.*maior que a fresa/);
    // rectangle cannot be drilled: option only exists for circles
    await page.getByTestId("add-rectangle").click();
    await expect(page.getByTestId("shape-operation").locator("option[value=drill]")).toHaveCount(0);
  });

  test("helix entry on pockets removes the vertical plunge and the time estimate uses acceleration", async ({ page }) => {
    await page.goto("/");
    await page.getByTestId("add-rectangle").click();
    await page.getByTestId("shape-operation").selectOption("pocket");
    await page.getByTestId("section-toggle-cut").click();
    const before = await exportGcode(page);
    await page.getByTestId("helix-entry").check();
    await expect(page.getByTestId("helix-pitch")).toBeVisible();
    const after = await exportGcode(page);
    const firstZ = (t: string) => t.split("\n").find((l) => /^G1 .*Z-/.test(l)) ?? "";
    expect(firstZ(before.text)).toMatch(/^G1 Z-/);
    expect(firstZ(after.text)).toMatch(/^G1 X.* Y.* Z-/);
    expect(after.text).toMatch(/tempo estimado: .*accel 200 mm\/s²/);
    // turning acceleration off shortens the estimate
    const t1 = after.text.match(/tempo estimado: ([^ ]+)/)?.[1];
    await page.getByTestId("accel").fill("0");
    await page.getByTestId("accel").press("Enter");
    const c = await exportGcode(page);
    expect(c.text).not.toContain("accel");
    const t2 = c.text.match(/tempo estimado: ([^ ]+)/)?.[1];
    expect(t1).not.toBe(t2);
  });
});

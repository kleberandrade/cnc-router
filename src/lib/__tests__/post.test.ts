import { describe, it, expect } from "vitest";
import { generateGCode, segmentsToGCode } from "../gcode";
import { POSTS, findPost, fmtNum, unitScale } from "../post";
import { DEFAULT_MACHINE_SETTINGS, type Shape } from "../../types";

const shapes: Shape[] = [
  { id: "r", kind: "rectangle", x: 20, y: 20, width: 40, height: 30, rotation: 0, depth: 3, operation: "outline" },
];
const two: Shape[] = [
  ...shapes,
  { id: "c", kind: "circle", x: 100, y: 60, radius: 5, depth: 3, operation: "outline", toolId: "t2" },
];
const withTools = { ...DEFAULT_MACHINE_SETTINGS, tools: [{ id: "t2", name: "Fresa 3mm", type: "flat" as const, diameter: 3, vbitAngle: 90 }] };

describe("pós-processadores", () => {
  it("lista GRBL, Marlin e LinuxCNC; desconhecido cai para GRBL", () => {
    expect(POSTS.map((p) => p.id)).toEqual(["grbl", "marlin", "linuxcnc"]);
    expect(findPost("xyz").id).toBe("grbl");
  });
  it("GRBL: ';' comentários, M3/M5, M0 na troca, M2 no fim", () => {
    const g = generateGCode(two, { ...withTools, post: "grbl" });
    expect(g).toContain("; Generated by Oficina CNC");
    expect(g).toContain("G21 ; millimeters");
    expect(g).toMatch(/M3 S12000 ; spindle on/);
    expect(g).toContain("M0 ; TROCA DE FERRAMENTA: Fresa 3mm (Ø3 mm)");
    expect(g.trim().endsWith("M2 ; program end")).toBe(true);
    expect(g.split("\n").some((l) => l.startsWith("("))).toBe(false);
  });
  it("Marlin: M117, G4 após M3, M0 com mensagem, M400/M84 no fim, sem M2/G28", () => {
    const g = generateGCode(two, { ...withTools, post: "marlin" });
    expect(g).toContain("M117 Oficina CNC");
    expect(g).toMatch(/M3 S12000[^\n]*\nG4 S2/);
    expect(g).toContain("M0 Troca: Fresa 3mm O3mm");
    expect(g).toContain("M400");
    expect(g.trim().endsWith("M84 ; desliga motores")).toBe(true);
    expect(g).not.toMatch(/^M2\b/m);
    expect(g).not.toContain("G28");
  });
  it("LinuxCNC: comentários entre parênteses, G17/G40/G49/G64, (MSG,…) + M0, M30", () => {
    const g = generateGCode(two, { ...withTools, post: "linuxcnc" });
    expect(g).toContain("(Generated by Oficina CNC");
    expect(g).toContain("G21 (millimeters)");
    expect(g).toContain("G64 P0.01");
    expect(g).toContain("(MSG, TROCA DE FERRAMENTA: Fresa 3mm O3 mm)");
    expect(g).toContain("M0 (pausa");
    expect(g.trim().endsWith("M30 (program end)")).toBe(true);
    // no ';' comments at all
    expect(g.split("\n").some((l) => l.includes(";"))).toBe(false);
    // parentheses inside comments are stripped so the comment stays valid
    expect(g).not.toMatch(/\([^)]*\([^)]*\)/);
  });
  it("todos os pós produzem só G0/G1/G4/G17/G20/G21/G40/G49/G64/G90/M-codes/comentários", () => {
    for (const p of POSTS) {
      const g = generateGCode(two, { ...withTools, post: p.id });
      for (const line of g.split("\n").filter(Boolean)) {
        expect(line).toMatch(/^(;|\(|G0 |G1 |G4 |G17|G20|G21|G40|G49|G64|G90|M\d)/);
      }
    }
  });
});

describe("G20 (polegadas)", () => {
  it("converte coordenadas e avanços por 25,4 e emite G20", () => {
    const mm = generateGCode(shapes, DEFAULT_MACHINE_SETTINGS);
    const inch = generateGCode(shapes, { ...DEFAULT_MACHINE_SETTINGS, exportUnits: "inch" });
    expect(inch).toContain("G20 ; inches");
    expect(inch).not.toContain("G21");
    // rectangle corner at (20,20) mm → 0.7874 in; feed 800 mm/min → 31.4961 in/min
    expect(mm).toContain("G0 X20 Y20");
    expect(inch).toContain("G0 X0.7874 Y0.7874");
    expect(inch).toMatch(/F31\.4961/);
    expect(inch).toContain("G0 Z0.1969"); // safe height 5 mm
    // same number of motion lines
    const motion = (g: string) => g.split("\n").filter((l) => /^G[01] /.test(l)).length;
    expect(motion(inch)).toBe(motion(mm));
  });
  it("segmentsToGCode escala com 4 casas em polegadas", () => {
    const lines = segmentsToGCode(
      [{ from: [0, 0, 0], to: [25.4, 0, -25.4], type: "feed", feed: 254, shapeId: null, pass: 0, op: "travel" }],
      { scale: unitScale("inch") }
    );
    expect(lines).toEqual(["G1 X1 Y0 Z-1 F10"]);
    expect(fmtNum(0.78740157, 4)).toBe("0.7874");
    expect(fmtNum(2, 4)).toBe("2");
  });
});

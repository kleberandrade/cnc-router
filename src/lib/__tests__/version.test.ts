import { describe, it, expect } from "vitest";
import { APP_VERSION, versionLabel, buildLabel, isNewVersion, isFirstRun, markVersionSeen, CHANGELOG } from "../version";
import { generateGCode } from "../gcode";
import { DEFAULT_MACHINE_SETTINGS } from "../../types";

const mem = () => { const m = new Map<string, string>(); return { getItem: (k: string) => m.get(k) ?? null, setItem: (k: string, v: string) => { m.set(k, v); } }; };

describe("version", () => {
  it("labels contain the semver from package.json (or the test fallback)", () => {
    expect(versionLabel()).toBe(`v${APP_VERSION}`);
    expect(buildLabel()).toMatch(/^v\d+\.\d+\.\d+.*\(/);
    expect(Array.isArray(CHANGELOG)).toBe(true);
  });
  it("first run: nothing seen; after marking, not new; different stored version → new", () => {
    const st = mem();
    expect(isFirstRun(st)).toBe(true);
    expect(isNewVersion(st)).toBe(false);
    markVersionSeen(st);
    expect(isFirstRun(st)).toBe(false);
    expect(isNewVersion(st)).toBe(false);
    st.setItem("oficina-cnc:seen-version", "0.0.1");
    expect(isNewVersion(st)).toBe(true);
    expect(isNewVersion(null)).toBe(false);
  });
  it("G-code header carries product, version and author", () => {
    const g = generateGCode([{ id: "r", kind: "rectangle", x: 10, y: 10, width: 20, height: 10, rotation: 0, depth: 2, operation: "outline" }], DEFAULT_MACHINE_SETTINGS);
    expect(g.split("\n")[0]).toMatch(/^; Generated by Oficina CNC v\d+\.\d+\.\d+ \(.+\) — Kleber Andrade — https:\/\/oficina-cnc\.vercel\.app$/);
  });
});
